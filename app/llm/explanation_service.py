from __future__ import annotations

import json
from typing import Any

from app.comparison.explainability import ExplainabilityService
from app.llm.base import LLMMessage, create_system_message, create_user_message
from app.llm.prompts.comparison import (
    LLM_RISK_CHANGE_EXPLANATION_PROMPT,
    LLM_RISK_CHANGE_EXPLANATION_SYSTEM_PROMPT,
)
from app.llm.provider_factory import get_default_llm
from app.models.comparison import RiskEvolutionRecord
from app.models.explainability import ExplainableRiskEvolution


class LLMExplanationService:
    """Adds optional evidence-grounded LLM wording to deterministic explanations."""

    def __init__(self, provider=None):
        self.provider = provider or get_default_llm()
        self.deterministic = ExplainabilityService()

    async def explain_records(
        self,
        records: list[RiskEvolutionRecord],
        company_name: str = "the company",
    ) -> list[ExplainableRiskEvolution]:
        results = []
        for record in records:
            results.append(await self.explain_record(record, company_name))
        return results

    async def explain_record(
        self,
        record: RiskEvolutionRecord,
        company_name: str,
    ) -> ExplainableRiskEvolution:
        explanation = self.deterministic.explain_record(record)
        if not self.provider or not self.provider.is_available():
            return explanation

        try:
            payload = self._prompt_payload(record, company_name)
            response = await self.provider.generate(
                [
                    create_system_message(LLM_RISK_CHANGE_EXPLANATION_SYSTEM_PROMPT),
                    create_user_message(LLM_RISK_CHANGE_EXPLANATION_PROMPT.format(**payload)),
                ]
            )
            generated = self._parse_json(response.content)
            if not generated:
                return explanation

            # Preserve evidence, confidence, and source record from the deterministic layer.
            explanation.why_it_matters.text = generated["why_it_matters"]
            explanation.executive_summary.text = generated["what_changed"]
            explanation.business_impact.text = generated["business_impact"]
            explanation.confidence_reason = (
                f"LLM explanation generated by {response.metadata.get('provider', 'configured provider')} "
                "and grounded in the cited report evidence."
            )
            return explanation
        except Exception:
            # LLM availability must never remove the evidence-backed result.
            return explanation

    @staticmethod
    def _prompt_payload(record: RiskEvolutionRecord, company_name: str) -> dict[str, Any]:
        def evidence_text(evidence) -> str:
            if evidence is None:
                return "No evidence supplied."
            return f"Page {evidence.page}: {evidence.text[:2000]}"

        return {
            "company_name": company_name,
            "change_type": record.change_type.value,
            "previous_year": record.report_year_prev or "unknown",
            "current_year": record.report_year_current or "unknown",
            "category": (record.metadata or {}).get("category", "unknown"),
            "previous_severity": record.severity_prev or "unknown",
            "current_severity": record.severity_current or "unknown",
            "semantic_similarity": record.semantic_similarity,
            "previous_evidence": evidence_text(record.evidence_prev),
            "current_evidence": evidence_text(record.evidence_current),
        }

    @staticmethod
    def _parse_json(content: str) -> dict[str, str] | None:
        text = content.strip()
        if text.startswith("```"):
            text = text.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
        try:
            value = json.loads(text)
        except json.JSONDecodeError:
            return None
        required = {"what_changed", "why_it_matters", "business_impact"}
        if not isinstance(value, dict) or not required.issubset(value):
            return None
        if not all(isinstance(value[key], str) and value[key].strip() for key in required):
            return None
        return {key: value[key].strip() for key in required}
